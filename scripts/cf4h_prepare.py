#!/usr/bin/env python3
"""Verify, preprocess and assemble the 4-hour counterfactual Control-IQ dataset.

Two independent simulator trees are combined:
  * eff4h   -- factual + 8 basal scales + the 6 original bolus specs
  * bolus4h -- factual + the 13-dose add-average bolus menu (0.00x .. 3.00x)

The factual prefixes are unchanged from the 2h dataset (only the counterfactual
horizon grew), so train/val and test_prefix are carried over from it verbatim and
seq_ids are remapped onto it. Nothing existing is modified: output is a new dataset.
"""
from __future__ import annotations
import argparse, json, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np
import pandas as pd

TEST_PATIENTS = [2,4,12,21,25,33,41,44,45,48,68,71,72,76,80,86,87,91,97,99]
SUFFIX_ROWS_4H = 49          # 48 five-minute steps + the t=0 boundary row
BOLUS_MENU = [f"bolus_add_avg_{s:.2f}x" for s in np.arange(0.0, 3.001, 0.25)]


def verify_raw(raw: Path, tag: str, require_all: bool) -> list[int]:
    """Every patient must have episodes whose manifest-declared valid scenarios all
    exist on disk with the full 4h suffix length."""
    ok, bad = [], []
    for pid in TEST_PATIENTS:
        d = raw / f"patient_{pid:03d}"
        if not d.is_dir():
            bad.append((pid, "no dir")); continue
        eps = sorted(x for x in d.glob("episode_*") if x.is_dir())
        if not eps:
            bad.append((pid, "no episodes")); continue
        trouble = None
        for ep in eps:
            man = ep / "manifest.csv"
            if not man.exists() or not (ep / "prefix_factual.csv").exists():
                trouble = f"{ep.name}: missing manifest/prefix"; break
            m = pd.read_csv(man)
            valid = m[pd.to_numeric(m.is_valid, errors="coerce").fillna(0).astype(int) == 1]
            for name in valid.scenario_name:
                f = ep / f"suffix_{name}.csv"
                if not f.exists():
                    trouble = f"{ep.name}: missing suffix_{name}.csv"; break
            if trouble: break
        if trouble: bad.append((pid, trouble))
        else: ok.append(pid)
    print(f"[verify:{tag}] complete patients: {len(ok)}/{len(TEST_PATIENTS)}", flush=True)
    for pid, why in bad:
        print(f"[verify:{tag}]   INCOMPLETE patient {pid}: {why}", flush=True)
    if bad and require_all:
        sys.exit(f"[verify:{tag}] FAIL: {len(bad)} patients incomplete")
    return ok


def verify_horizon(raw: Path, tag: str, pids: list[int]) -> None:
    """Every suffix must carry the full 4h horizon; a short one means the episode was
    generated by the old 2h script and would silently truncate the evaluation."""
    lens, checked = set(), 0
    for pid in pids[:5]:
        for ep in sorted((raw / f"patient_{pid:03d}").glob("episode_*")):
            for f in sorted(ep.glob("suffix_*.csv")):
                lens.add(sum(1 for _ in f.open()) - 1); checked += 1
    print(f"[verify:{tag}] suffix row counts across {checked} files: {sorted(lens)}", flush=True)
    if lens != {SUFFIX_ROWS_4H}:
        sys.exit(f"[verify:{tag}] FAIL: expected every suffix to have {SUFFIX_ROWS_4H} rows, got {sorted(lens)}")


def preprocess(raw: Path, out: Path, name: str, pids: list[int]) -> None:
    from preprocessing.action_cf_benchmark import _preprocess_action_cf_like
    # The collector walks every patient in splits.csv; this tree holds only the test
    # split, so write a restricted file naming exactly the patients present.
    pd.DataFrame({"pat_id": pids, "split": ["test"] * len(pids)}).to_csv(raw / "splits.csv", index=False)
    print(f"[preprocess] {raw} -> {out}", flush=True)
    _preprocess_action_cf_like(raw_dir=raw, output_dir=out, dataset_name=name,
                               notes="4-hour counterfactual horizon on the Control-IQ episodes.")


def seq_map(new_proc: Path, old_proc: Path) -> dict:
    """seq_id is a global counter assigned at preprocessing time, so the same episode
    carries different ids in different datasets. Map on (pat_id, episode_id)."""
    n = pd.read_csv(new_proc / "test_scenarios.csv")[["pat_id","seq_id","episode_id"]].drop_duplicates()
    o = pd.read_csv(old_proc / "test_scenarios.csv")[["pat_id","seq_id","episode_id"]].drop_duplicates()
    m = n.merge(o.rename(columns={"seq_id": "old_seq"}), on=["pat_id","episode_id"], how="inner")
    return dict(zip(zip(m.pat_id, m.seq_id), m.old_seq))


def _prefix_keys(proc: Path, smap: dict | None = None):
    a = pd.read_csv(proc / "test_prefix.csv").copy()
    if smap is not None:
        a["seq_id"] = [smap.get((p, s), -1) for p, s in zip(a.pat_id, a.seq_id)]
        a = a[a.seq_id >= 0]
    return a.groupby(["pat_id", "seq_id"])["cgm"].agg(["count", "sum"])


def verify_eff_bol_agree(eff_proc: Path, bol_proc: Path, smap_bol_to_eff: dict) -> None:
    """The two trees are independent simulator runs. They must place episodes identically
    and produce identical factual prefixes, or their scenarios cannot share a prefix."""
    ka = _prefix_keys(eff_proc)
    kb = _prefix_keys(bol_proc, smap_bol_to_eff)
    common = ka.index.intersection(kb.index)
    ca, cb = ka.loc[common], kb.loc[common]
    rel = (ca["sum"] - cb["sum"]).abs() / cb["sum"].abs().clip(lower=1.0)
    same = int(((ca["count"] == cb["count"]) & (rel < 1e-4)).sum())
    print(f"[verify] eff/bolus agreement: {len(common)} shared episodes, {same} identical prefixes "
          f"(max rel diff {rel.max():.2e})", flush=True)
    if len(common) == 0 or same != len(common):
        sys.exit(f"[verify] FAIL: {len(common)-same} episodes differ between the two 4h trees")


def report_shift_vs_2h(eff_proc: Path, old_proc: Path, smap_eff_to_old: dict) -> None:
    """Episode placement enforces non-overlap with the previous perturbation window, so
    doubling the horizon moves some episodes. Not an error -- but it means the 4h episodes
    are not all literally the ones used at 2h, which belongs in the paper."""
    ka = _prefix_keys(eff_proc, smap_eff_to_old)
    kb = _prefix_keys(old_proc)
    common = ka.index.intersection(kb.index)
    if not len(common):
        print("[report] no episodes shared with the 2h dataset", flush=True); return
    ca, cb = ka.loc[common], kb.loc[common]
    rel = (ca["sum"] - cb["sum"]).abs() / cb["sum"].abs().clip(lower=1.0)
    same = int(((ca["count"] == cb["count"]) & (rel < 1e-4)).sum())
    print(f"[report] vs 2h dataset: {same}/{len(common)} episodes sit at the identical window; "
          f"{len(common)-same} shifted because the non-overlap constraint scales with the horizon",
          flush=True)


def assemble(eff_proc: Path, bol_proc: Path, old_proc: Path, out: Path,
             smap_bol: dict) -> None:
    out.mkdir(parents=True, exist_ok=True)
    # train/val are full factual series, unaffected by episode placement.
    for f in ["train.csv", "val.csv"]:
        shutil.copy(old_proc / f, out / f)
        print(f"[assemble] carried over {f} from the 2h dataset", flush=True)
    # test_prefix MUST come from the 4h tree: some episodes moved, so the 2h prefixes
    # would no longer be the history the 4h suffixes actually continue from.
    shutil.copy(eff_proc / "test_prefix.csv", out / "test_prefix.csv")
    print("[assemble] test_prefix.csv taken from the 4h tree (episodes can shift)", flush=True)

    for name in ["test_scenarios.csv", "test_suffix.csv"]:
        eff = pd.read_csv(eff_proc / name)
        bol = pd.read_csv(bol_proc / name)
        bol["seq_id"] = [smap_bol.get((p, s), -1) for p, s in zip(bol.pat_id, bol.seq_id)]
        # eff contributes factual + basal + the original bolus specs;
        # bol contributes only the add-average dose menu (its factual would duplicate).
        bol = bol[bol.scenario_name.isin(BOLUS_MENU)]
        n_drop = int((bol.seq_id < 0).sum())
        bol = bol[bol.seq_id >= 0]
        both = pd.concat([eff, bol], ignore_index=True).drop_duplicates()
        both.to_csv(out / name, index=False)
        print(f"[assemble] {name}: eff {len(eff)} + bolus {len(bol)} -> {len(both)}"
              + (f"  (dropped {n_drop} unmapped)" if n_drop else ""), flush=True)

    meta = json.loads((old_proc / "metadata.json").read_text())
    meta["notes"] = (meta.get("notes", "") +
                     " REGENERATED: counterfactual horizon extended from 2h to 4h; bolus menu "
                     "widened to a 13-dose add-average grid (0-3x) and basal to 8 scales (0-4x).")
    meta["counterfactual_horizon_minutes"] = 240
    meta["basal_menu"] = ["0x","0.5x","1.5x","2x","2.5x","3x","3.5x","4x"]
    meta["bolus_menu"] = BOLUS_MENU
    (out / "metadata.json").write_text(json.dumps(meta, indent=2))

    sc = pd.read_csv(out / "test_scenarios.csv")
    sfx = pd.read_csv(out / "test_suffix.csv")
    print("\n[report] scenarios by family:\n", sc.perturb_family.value_counts().to_string(), flush=True)
    print("[report] episodes:", sc[sc.scenario_type == "factual"].shape[0], flush=True)
    for fam in ["basal", "bolus"]:
        g = sc[(sc.perturb_family == fam) & (sc.scenario_type == "counterfactual")]
        per = g.groupby(["pat_id","seq_id","episode_id"]).size()
        print(f"[report] {fam}: {per.size} episodes, menu sizes {sorted(per.unique())}", flush=True)
    rows = sfx.groupby(["pat_id","seq_id","scenario_name"]).size()
    print(f"[report] suffix rows per scenario: {sorted(rows.unique())} (expect [{SUFFIX_ROWS_4H}])", flush=True)
    if set(rows.unique()) != {SUFFIX_ROWS_4H}:
        sys.exit(f"[report] FAIL: suffix lengths are not uniformly {SUFFIX_ROWS_4H}")


def main():
    T = Path("/project/shakeri-lab/Alireza_timeseries/sim-prep/UVA-T1D-Simulator/TestAID")
    p = argparse.ArgumentParser()
    p.add_argument("--raw-eff", type=Path, default=T / "action_cf_controliq_4h")
    p.add_argument("--raw-bol", type=Path, default=T / "action_cf_bolus_controliq_4h")
    p.add_argument("--old-proc", type=Path, default=Path("datasets_processed/action_cf_benchmark_controliq"))
    p.add_argument("--eff-proc", type=Path, default=Path("datasets_processed/action_cf_controliq_4h_eff"))
    p.add_argument("--bol-proc", type=Path, default=Path("datasets_processed/action_cf_controliq_4h_bol"))
    p.add_argument("--out", type=Path, default=Path("datasets_processed/action_cf_controliq_4h"))
    p.add_argument("--require-all", action="store_true")
    p.add_argument("--skip-preprocess", action="store_true")
    a = p.parse_args()

    pe = verify_raw(a.raw_eff, "eff4h", a.require_all)
    pb = verify_raw(a.raw_bol, "bolus4h", a.require_all)
    if not pe or not pb:
        sys.exit("[verify] FAIL: no complete patients")
    verify_horizon(a.raw_eff, "eff4h", pe)
    verify_horizon(a.raw_bol, "bolus4h", pb)

    if not a.skip_preprocess:
        preprocess(a.raw_eff, a.eff_proc, "action_cf_controliq_4h_eff", pe)
        preprocess(a.raw_bol, a.bol_proc, "action_cf_controliq_4h_bol", pb)

    mb = seq_map(a.bol_proc, a.eff_proc)          # bolus tree -> eff tree ids
    me = seq_map(a.eff_proc, a.old_proc)          # eff tree -> 2h ids, for reporting only
    verify_eff_bol_agree(a.eff_proc, a.bol_proc, mb)
    report_shift_vs_2h(a.eff_proc, a.old_proc, me)
    assemble(a.eff_proc, a.bol_proc, a.old_proc, a.out, mb)
    print("\n[done] 4h dataset at", a.out, flush=True)


if __name__ == "__main__":
    main()
